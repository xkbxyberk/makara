"""Generate the local test media and the synthetic info dict that points at it.

Everything is produced with FFmpeg's `testsrc`/`sine` sources, so download tests exercise the
real yt-dlp + FFmpeg pipeline over HTTP on 127.0.0.1 without ever reaching the internet.
The output is deterministic and idempotent; run it as often as you like.

    uv run python scripts/make_test_media.py
"""

from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

MEDIA_DIR = Path(__file__).resolve().parent.parent / "tests" / "fixtures" / "media"
DURATION = 4  # seconds; long enough for two chapters, short enough to transcode instantly
MEDIA_VERSION = 2  # bump when the generated set changes; tests regenerate on mismatch

# FFmpeg can write TTML but cannot read it: a subtitle a site may hand over that we cannot mux.
TTML = """<?xml version="1.0" encoding="utf-8"?>
<tt xmlns="http://www.w3.org/ns/ttml"><body><div>
<p begin="00:00:00.000" end="00:00:01.800">テストクリップ</p>
</div></body></tt>
"""
BASE = "{base}"  # replaced with the serving URL at load time

VTT = """WEBVTT

00:00:00.000 --> 00:00:01.800
{a}

00:00:02.000 --> 00:00:03.800
{b}
"""

SUBS = {
    "en": ("Hello from the test clip.", "This is the second line."),
    "tr": ("Test klibinden merhaba.", "Bu ikinci satır."),
    "de": ("Hallo aus dem Testclip.", "Das ist die zweite Zeile."),
}


def ffmpeg(*args: str) -> None:
    argv = ["ffmpeg", "-hide_banner", "-loglevel", "error", "-y", *args]
    subprocess.run(argv, check=True)


def build_media() -> None:
    MEDIA_DIR.mkdir(parents=True, exist_ok=True)
    src = f"testsrc2=size=640x360:rate=25:duration={DURATION}"
    ffmpeg(
        "-f",
        "lavfi",
        "-i",
        src,
        "-c:v",
        "libvpx-vp9",
        "-b:v",
        "300k",
        "-an",
        str(MEDIA_DIR / "video_vp9.webm"),
    )
    ffmpeg(
        "-f",
        "lavfi",
        "-i",
        f"testsrc2=size=426x240:rate=25:duration={DURATION}",
        "-c:v",
        "libx264",
        "-pix_fmt",
        "yuv420p",
        "-g",
        "25",
        "-an",
        str(MEDIA_DIR / "video_h264.mp4"),
    )
    for lang, freq in (("en", 440), ("tr", 660), ("de", 880)):
        ffmpeg(
            "-f",
            "lavfi",
            "-i",
            f"sine=frequency={freq}:duration={DURATION}",
            "-c:a",
            "aac",
            "-b:a",
            "96k",
            str(MEDIA_DIR / f"audio_{lang}.m4a"),
        )
    ffmpeg(
        "-f",
        "lavfi",
        "-i",
        f"sine=frequency=440:duration={DURATION}",
        "-c:a",
        "libopus",
        "-b:a",
        "96k",
        str(MEDIA_DIR / "audio_en.webm"),
    )
    ffmpeg(
        "-f",
        "lavfi",
        "-i",
        "testsrc2=size=640x360:rate=1:duration=1",
        "-frames:v",
        "1",
        str(MEDIA_DIR / "thumb.jpg"),
    )
    for lang, (a, b) in SUBS.items():
        (MEDIA_DIR / f"sub_{lang}.vtt").write_text(VTT.format(a=a, b=b), encoding="utf-8")
    (MEDIA_DIR / "sub_ja.ttml").write_text(TTML, encoding="utf-8")


def fmt(name: str, **fields: object) -> dict[str, object]:
    size = (MEDIA_DIR / name).stat().st_size
    return {
        "url": f"{BASE}/{name}",
        "filesize": size,
        "tbr": round(size * 8 / 1000 / DURATION, 1),
        "protocol": "http",
        **fields,
    }


def sub(name: str, query: str = "", ext: str = "vtt") -> list[dict[str, str]]:
    return [{"ext": ext, "url": f"{BASE}/{name}{query}"}]


